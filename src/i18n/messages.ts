const catalogs: Record<Locale, Record<MessageKey, string>> = { en, ru };

export const MESSAGE_KEYS = Object.keys(en) as MessageKey[];

// The forms of "minute" after a number, as in how long something works: in Russian, as after «действует» (1 минуту,
// 2 минуты, 5 минут, 21 минуту). Intl.PluralRules picks the form for the number.
const MINUTE_FORMS: Record<Locale, Partial<Record<Intl.LDMLPluralRule, string>> & { other: string }> = {
  en: { one: "minute", other: "minutes" },
  ru: { one: "минуту", few: "минуты", many: "минут", other: "минуты" },
};

// A duration in whole minutes, with the word in the form its number needs: "15 minutes", "15 минут".
export function formatMinutes(locale: Locale, ms: number): string {
  const minutes = Math.round(ms / 60_000);
  const forms = MINUTE_FORMS[locale];
  return `${minutes} ${forms[new Intl.PluralRules(locale).select(minutes)] ?? forms.other}`;
}

// Returns plain text: callers escape it for HTML. A placeholder without a value stays visible, so a missing value
// shows up in a test instead of silently disappearing.
export function translate(
  locale: Locale,
  key: MessageKey,
  vars: Readonly<Record<string, string | number>> = {},
): string {
  return catalogs[locale][key].replace(/\{(\w+)\}/gu, (placeholder, name: string) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : placeholder);
}
